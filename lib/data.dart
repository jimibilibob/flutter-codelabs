import 'dart:convert';

class Document {
  final Map<String, Object?> _json;
  Document() : _json = jsonDecode(documentJson);

  (String, {DateTime modified}) get metadata {
    if(_json case {'metadata': {'title': String title, 'modified': String modified}}) {
      return (title, modified: DateTime.parse(modified));
    }
    throw const FormatException('Unexpected JSON format');
  }

  List<Block> get blocks {
    if(_json case {'blocks': List blocks}) {
      return [for(final block in blocks) Block.fromJson(block)];
    }
    throw const FormatException('Unexpected JSON format');
  }
}

const documentJson = '''
{
  "metadata": {
    "title": "My Document",
    "modified": "2023-05-10"
  },
  "blocks": [
    {
      "type": "h1",
      "text": "Chapter 1"
    },
    {
      "type": "p",
      "text": "Lorem ipsum dolor sit amet, consectetur adipiscing elit."
    },
    {
      "type": "checkbox",
      "checked": false,
      "text": "Learn Dart 3"
    }
  ]
}
''';

sealed class Block {

  Block();

  factory Block.fromJson(Map<String, Object?> json) {
    return switch (json) {
      {'type': 'h1', 'text': String text} => HeaderBlock(text),
      {'type': 'p', 'text': String text} => ParagraphBlock(text),
      {'type': 'checkbox', 'checked': bool isChecked, 'text': String text} => CheckboxBlock(text, isChecked),
      _ => throw const FormatException('Unexpected JSON format')
    };
  }
}

class HeaderBlock extends Block {
  final String text;
  HeaderBlock(this.text);
}

class ParagraphBlock extends Block {
  final String text;
  ParagraphBlock(this.text);
}

class CheckboxBlock extends Block {
  final String text;
  final bool isChecked;
  CheckboxBlock(this.text, this.isChecked);
}
